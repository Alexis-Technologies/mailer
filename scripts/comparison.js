/**
 * The feature matrices of the comparison pages, each one table with
 * @alexify/mailer and the alternatives in columns, the features in rows
 * grouped by area: docs/comparison.json into docs/guide/comparison.md (the
 * email libraries), and docs/comparison-channels.json into
 * docs/guide/comparison-channels.md (the libraries of SMS, chat apps and
 * push). Each is rendered into the region between `<!-- comparison:start -->`
 * and `<!-- comparison:end -->` of its page, so the table and the data cannot
 * drift (CI regenerates both and fails on a diff). A cell is
 * `{ mark, text, note? }`: the mark is one of ✅ ⚠️ ❌ 🔜 —, the text a few
 * words (backticks become code), and a note becomes a numbered footnote under
 * the table.
 *
 * The first library of the data is @alexify/mailer: custom.css tints the
 * second column of the table in the brand colour and pins it beside the
 * features. Every cell of the data was decided by reading the source of the
 * project (see the page for the method); edit the data, not the table.
 *
 * Run: pnpm docs:comparison
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
// Each data file and the page it is rendered into.
const PAIRS = [
  { data: 'docs/comparison.json', page: 'docs/guide/comparison.md' },
  { data: 'docs/comparison-channels.json', page: 'docs/guide/comparison-channels.md' },
];
const START = '<!-- comparison:start -->';
const END = '<!-- comparison:end -->';
const generatedFrom = (data) =>
  `<!-- generated by \`pnpm docs:comparison\` from ${data} — edit the data, not this block -->`;

const escape = (text) =>
  String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// `code` spans and [links](url), the only markup a cell or a note uses.
const inline = (text) =>
  escape(text)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>');

const render = (data) => {
  const notes = [];
  const noteOf = (text) => {
    let index = notes.indexOf(text);
    if (index === -1) index = notes.push(text) - 1;
    return `<sup>${index + 1}</sup>`;
  };
  const columns = data.libraries;
  const lines = ['<table>', '<thead>', '<tr>', '<th>Feature</th>'];
  for (const library of columns) {
    const name = `<a href="${library.url}">${escape(library.name)}</a>`;
    lines.push(`<th>${name}<br><sub>${escape(library.direction)}</sub></th>`);
  }
  lines.push('</tr>', '</thead>', '<tbody>');
  for (const group of data.groups) {
    lines.push(
      `<tr class="ml-matrix-group"><td colspan="${columns.length + 1}"><strong>${escape(group.title)}</strong></td></tr>`,
    );
    for (const row of group.rows) {
      const cells = [`<td>${inline(row.title)}</td>`];
      for (const library of columns) {
        const cell = library.cells[row.id];
        if (!cell) throw new Error(`${library.id}: no cell for "${row.id}"`);
        const parts = [];
        if (cell.mark) parts.push(cell.mark);
        if (cell.text) parts.push(inline(cell.text));
        const note = cell.note ? noteOf(cell.note) : '';
        cells.push(`<td>${parts.join(' ')}${note}</td>`);
      }
      lines.push(`<tr>${cells.join('')}</tr>`);
    }
  }
  lines.push('</tbody>', '</table>');
  const list = notes.map((text, i) => `${i + 1}. ${inline(text)}`).join('\n');
  return { table: lines.join('\n'), notes: list };
};

const renderPair = (pair) => {
  const data = JSON.parse(fs.readFileSync(path.join(ROOT, pair.data), 'utf8'));
  const { table, notes } = render(data);
  const content = [`<div class="ml-matrix">\n\n${table}\n\n</div>`, data.legend, notes].join(
    '\n\n',
  );
  const file = path.join(ROOT, pair.page);
  const text = fs.readFileSync(file, 'utf8');
  const from = text.indexOf(START);
  const to = text.indexOf(END);
  if (from === -1 || to === -1) throw new Error(`${pair.page}: no comparison markers`);
  const generated = generatedFrom(pair.data);
  const next = `${text.slice(0, from + START.length)}\n${generated}\n\n${content}\n\n${text.slice(to)}`;
  fs.writeFileSync(file, next);
  console.log(`updated ${pair.page}`);
};

const main = () => {
  for (const pair of PAIRS) renderPair(pair);
};

main();
